#!/usr/bin/env python3
"""Turn the design system's tokens into a Dart file for the Flutter app.

    python3 tokens_to_dart.py <path to tds/> [output.dart]

Reads tds/foundations/tokens/tokens.json and tds/foundations/styles/type.json (the same files the CSS is built from), so the app and
the web never drift. Writes plain constants: colors, spacing, radius, blur, opacity, shadows, glow, containers, elevation, motion and the
text styles. Run it again whenever the tokens change; never edit the output by hand.
"""
import json, os, re, sys

if len(sys.argv) < 2:
    sys.exit(__doc__)
root = sys.argv[1]
out_path = sys.argv[2] if len(sys.argv) > 2 else 'tds_tokens.dart'
tokens = json.load(open(os.path.join(root, 'foundations/tokens/tokens.json')))['tokens']
types = json.load(open(os.path.join(root, 'foundations/styles/type.json')))['styles']
of = lambda k: [t for t in tokens if t['kind'] == k]
by = {t['name']: t for t in tokens}

def camel(name):
    p = re.split(r'[-_]', name)
    s = p[0] + ''.join(x[:1].upper() + x[1:] for x in p[1:])
    return s if not s[0].isdigit() else '_' + s

def num(n):
    n = float(n)
    return str(int(n)) if n == int(n) else repr(round(n, 4))

def dbl(n):
    return num(n) if '.' in num(n) else num(n) + '.0'

def color(hex_, opacity=100):
    h = hex_.lstrip('#')
    a = round(255 * opacity / 100)
    return 'Color(0x%02X%s)' % (a, h.upper())

prim = {t['name']: t['hex'] for t in of('primitive')}
families = {'inter': 'Inter', 'editorial': 'PP Editorial New', 'dm-mono': 'DM Mono'}

def role_color(r, mode):
    v = r['values'][mode]
    return color(prim[v['ref']], v.get('opacity', 100))

L = []
w = L.append
w('// GENERATED by skills/tds-app-dart/scripts/tokens_to_dart.py from the design system tokens. Do not edit; run the script again.')
w("import 'package:flutter/animation.dart';")
w("import 'package:flutter/painting.dart';")
w('')
w('/// Raw colors. Use the roles (TdsColors) in widgets, not these.')
w('abstract final class TdsPalette {')
for t in of('primitive'):
    w('  static const Color %s = %s;' % (camel(t['name']), color(t['hex'])))
w('}')
w('')
w('/// Color roles for one surface. `TdsColors.normal` is the dark app; `TdsColors.inverse` is for a white card on it (the coachmark).')
w('/// A role has a `-Inverse` companion: the color to use on the opposite surface.')
w('class TdsColors {')
roles = of('role')
w('  const TdsColors({')
for r in roles:
    w('    required this.%s,' % camel(r['name']))
    w('    required this.%sInverse,' % camel(r['name']))
w('  });')
for r in roles:
    w('  final Color %s;' % camel(r['name']))
    w('  final Color %sInverse;' % camel(r['name']))
for label, a, b in (('normal', 'base', 'inverse'), ('inverse', 'inverse', 'base')):
    w('  static const TdsColors %s = TdsColors(' % label)
    for r in roles:
        w('    %s: %s,' % (camel(r['name']), role_color(r, a)))
        w('    %sInverse: %s,' % (camel(r['name']), role_color(r, b)))
    w('  );')
w('}')
w('')
w('/// A named mesh gradient: a solid base with three soft corner glows that fade to transparent. Paint the base, then a RadialGradient for each glow')
w('/// (top right, top left, bottom right). `lightText` says whether text on it is white.')
w('class TdsMeshGradient {')
w('  const TdsMeshGradient({required this.base, required this.topRight, required this.topLeft, required this.bottomRight, required this.lightText});')
w('  final Color base, topRight, topLeft, bottomRight;')
w('  final bool lightText;')
for g in of('gradient'):
    w('  static const TdsMeshGradient %s = TdsMeshGradient(base: %s, topRight: %s, topLeft: %s, bottomRight: %s, lightText: %s);' % (
        camel(g['name'].replace('gradient-', '')), color(g['base']), color(g['topRight']), color(g['topLeft']), color(g['bottomRight']), 'true' if g['foreground'] == 'light' else 'false'))
w('}')
w('')
w('/// Spacing, padding, corner radius and background blur, all in logical pixels.')
w('abstract final class TdsSize {')
for k in ('padding', 'spacing', 'radius', 'blur'):
    for t in of(k):
        w('  static const double %s = %s;' % (camel(t['name']), dbl(t['px'])))
w('}')
w('')
w('/// Opacities used on their own (dimmed, disabled, muted, scrim).')
w('abstract final class TdsOpacity {')
for t in of('opacity'):
    w('  static const double %s = %s;' % (camel(t['name']), num(t['percent'] / 100)))
w('}')
w('')
w('abstract final class TdsShadow {')
for t in of('shadow'):
    w('  static const BoxShadow %s = BoxShadow(color: Color(0x%02X000000), offset: Offset(0, %s), blurRadius: %s);' % (camel(t['name']), round(255 * t['opacity'] / 100), dbl(t['y']), dbl(t['blur'])))
w('}')
w('')
w('/// How big, how blurred and how strong a glow is.')
w('class TdsGlow {')
w('  const TdsGlow({required this.size, required this.blur, required this.opacity});')
w('  final double size, blur, opacity;')
for t in of('glow'):
    w('  static const TdsGlow %s = TdsGlow(size: %s, blur: %s, opacity: %s);' % (camel(t['name'].replace('glow-', '')), dbl(t['size']), dbl(t['blur']), num(t['percent'] / 100)))
w('}')
w('')
w('/// Padding across and down, and the gap, of a box that holds things (the page, a card, an inset card, a sheet).')
w('class TdsContainer {')
w('  const TdsContainer({required this.padX, required this.padY, required this.gap});')
w('  final double padX, padY, gap;')
px = lambda name: dbl(by[name]['px']) if name in by else '0.0'
for t in of('container'):
    w('  static const TdsContainer %s = TdsContainer(padX: %s, padY: %s, gap: %s);' % (camel(t['name'].replace('container-', '')), px(t['padX']), px(t['padY']), px(t['gap'])))
w('}')
w('')
w('/// A surface: a fill, a background blur (sigma is half the CSS blur), a corner radius and a shadow, used together. Fills are for the dark surface.')
w('class TdsElevation {')
w('  const TdsElevation({required this.fill, required this.blur, required this.radius, this.shadow});')
w('  final Color fill;')
w('  final double blur, radius;')
w('  final BoxShadow? shadow;')
role_by = {r['name']: r for r in roles}
for t in of('elevation'):
    fill = role_color(role_by[t['fill']], 'base') if t['fill'] in role_by else 'Color(0x00000000)'
    blur = dbl(by[t['blur']]['px']) if t['blur'] in by else '0.0'
    rad = dbl(by[t['radius']]['px']) if t['radius'] in by else '0.0'
    sh = 'TdsShadow.%s' % camel(t['shadow']) if t['shadow'] in by else 'null'
    w('  static const TdsElevation %s = TdsElevation(fill: %s, blur: %s, radius: %s, shadow: %s);' % (camel(t['name'].replace('elevation-', 'level-') if t['name'][-1].isdigit() else t['name'].replace('elevation-', '')), fill, blur, rad, sh))
w('}')
w('')
w('abstract final class TdsDuration {')
for t in of('duration'):
    w('  static const Duration %s = Duration(milliseconds: %s);' % (camel(t['name'].replace('duration-', '')), num(t['ms'])))
w('}')
w('')
w('abstract final class TdsEasing {')
for t in of('easing'):
    w('  static const Cubic %s = Cubic(%s);' % (camel(t['name'].replace('ease-', '')), ', '.join(dbl(x) for x in t['bezier'])))
w('}')
w('')
w('/// The animation presets (fade in, enter, pop, scale in, draw, travel): how long, which curve, how much delay.')
w('class TdsMotion {')
w('  const TdsMotion({required this.duration, required this.curve, this.delay = Duration.zero});')
w('  final Duration duration;')
w('  final Curve curve;')
w('  final Duration delay;')
for t in of('motion'):
    d = camel(by[t['duration']]['name'].replace('duration-', '')); e = camel(by[t['easing']]['name'].replace('ease-', ''))
    w('  static const TdsMotion %s = TdsMotion(duration: TdsDuration.%s, curve: TdsEasing.%s, delay: Duration(milliseconds: %s));' % (camel(t['name'].replace('motion-', '')), d, e, num(t.get('delay', 0))))
w('}')
w('')
w('/// Text styles. Inter is a variable font here: the exact weight is set with a font variation, so 420 (Body) is really 420.')
w('abstract final class TdsText {')
wt = lambda v: 'FontWeight.w%d' % (max(1, min(9, round(v / 100))) * 100)
for s in types:
    fam = families.get(by[s['family']]['value'], 'Inter'); weight = by[s['weight']]['value']; size = by[s['size']]['px']
    lh = by[s['lineHeight']]['percent'] / 100; ls = by[s['letterSpacing']]['percent'] / 100 * size
    w('  /// %s: %s' % (s['name'], s.get('usage', '')))
    w('  static const TextStyle %s = TextStyle(fontFamily: %r, fontWeight: %s, fontVariations: [FontVariation(%r, %s)], fontSize: %s, height: %s, letterSpacing: %s%s);' % (
        camel(s['id']), fam, wt(weight), 'wght', dbl(weight), dbl(size), num(lh), num(ls), ', fontStyle: FontStyle.italic' if s.get('italic') else ''))
w('}')
open(out_path, 'w').write('\n'.join(L).replace("'Inter'", "'Inter'") + '\n')
print('wrote', out_path, len(L), 'lines')
