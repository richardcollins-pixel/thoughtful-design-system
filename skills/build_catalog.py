#!/usr/bin/env python3
"""Write the component catalog the skills read (a plain list of every component: what it is, its props, states and what it is built from).

    python3 skills/build_catalog.py

Run it after the design system changes, then commit the two copies it writes (tds-app-dart and tds-web)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TDS = os.path.join(ROOT, 'tds')
index = json.load(open(os.path.join(TDS, 'index.json')))['components']
TIERS = ['atoms', 'molecules', 'organisms', 'patterns', 'screens', 'device']
TITLE = {'atoms': 'Atoms', 'molecules': 'Molecules', 'organisms': 'Organisms', 'patterns': 'Patterns', 'screens': 'Screens (mobile app, for reference)', 'device': 'Device (the phone’s own chrome; never build these)'}

def meta(path):
    return json.load(open(os.path.join(TDS, path, os.path.basename(path) + '.meta.json')))

def props_line(m):
    ps = m.get('props') or {}
    out = []
    for k, v in ps.items():
        t = v.get('type')
        if t == 'enum': out.append('%s (%s)' % (k, ' | '.join(str(x) for x in v['values'])))
        else: out.append('%s (%s)' % (k, t))
    if not ps and m.get('attributes'):
        for k, v in m['attributes'].items():
            if v.get('type') == 'enum': out.append('%s (%s)' % (k, ' | '.join(str(x) for x in v['values'])))
    return ', '.join(out)

def states_line(m):
    st = m.get('states') or []
    if st and isinstance(st[0], dict): return ', '.join(s['id'] for s in st)
    return ', '.join(str(s) for s in st)

lines = ['# Component catalog', '', 'Generated by `skills/build_catalog.py` from every component’s `meta.json`. Do not edit. The `meta.json` (in `tds/<tier>/<name>/`) is the full source: markup or template, items, slots, overrides.', '',
         'Read the tiers in order: a component is only built from components in tiers above it in this list.', '']
by = {}
for p in index:
    by.setdefault(p.split('/')[0], []).append(p)
for tier in TIERS:
    if tier not in by: continue
    lines += ['## ' + TITLE[tier], '']
    for p in by[tier]:
        m = meta(p)
        lines.append('### `%s` — %s' % (p, m.get('name', p)))
        if m.get('description'): lines.append(m['description'])
        pl = props_line(m)
        if pl: lines.append('- Props: ' + pl)
        sl = states_line(m)
        if sl: lines.append('- States: ' + sl)
        if m.get('uses'): lines.append('- Built from: ' + ', '.join('`%s`' % u for u in m['uses']))
        if m.get('figma'): lines.append('- Figma: ' + m['figma'])
        lines.append('')
text = '\n'.join(lines)
for d in ('tds-app-dart', 'tds-web'):
    open(os.path.join(ROOT, 'skills', d, 'references', 'component-catalog.md'), 'w').write(text)
print('wrote catalog', len(lines), 'lines')
